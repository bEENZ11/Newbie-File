// Packs the built game (everything in dist) into the Worker, so the game and
// its room server are published together as one program with no separate
// file upload. Run after "vite build", and before deploying.

import { cpSync, mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const DIST = 'dist';
const OUT = join('server', 'site');
const TYPES = {
  html: 'text/html; charset=utf-8',
  js: 'text/javascript; charset=utf-8',
  css: 'text/css; charset=utf-8',
  json: 'application/json',
  gltf: 'model/gltf+json',
  glb: 'model/gltf-binary',
  md: 'text/markdown; charset=utf-8',
  png: 'image/png',
  jpg: 'image/jpeg',
  svg: 'image/svg+xml',
  ico: 'image/x-icon',
  mp3: 'audio/mpeg',
  ogg: 'audio/ogg',
};

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : [path];
  });
}

rmSync(OUT, { recursive: true, force: true });
mkdirSync(OUT, { recursive: true });

const files = walk(DIST).sort();
const imports = [];
const entries = [];
files.forEach((file, i) => {
  // Every file is copied under a neutral name, so the bundler treats it as plain data.
  cpSync(file, join(OUT, `${i}.bin`));
  const url = '/' + relative(DIST, file).split(sep).join('/');
  const type = TYPES[file.split('.').pop().toLowerCase()] ?? 'application/octet-stream';
  imports.push(`import f${i} from './site/${i}.bin';`);
  entries.push(`  ${JSON.stringify(url)}: { data: f${i}, type: ${JSON.stringify(type)} },`);
});

writeFileSync(
  join('server', 'site.gen.ts'),
  `// Generated by scripts/embed-site.mjs. Do not edit.\n${imports.join('\n')}\n\n` +
    `export const SITE: Record<string, { data: ArrayBuffer; type: string }> = {\n${entries.join('\n')}\n};\n`,
);
const total = files.reduce((sum, f) => sum + statSync(f).size, 0);
console.log(`Packed ${files.length} files (${(total / 1048576).toFixed(1)} MB) into the Worker.`);
